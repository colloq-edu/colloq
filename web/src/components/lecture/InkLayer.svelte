      paint.beginPath()
      paint.arc(points[0] * px, points[1] * py, line / 2, 0, Math.PI * 2)
      paint.fill()
      return
    }
    paint.strokeStyle = tint
    paint.lineWidth = line
    trace(paint, points, px, py)
    paint.stroke()
  }

