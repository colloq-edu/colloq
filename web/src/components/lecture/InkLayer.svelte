  </div>
  <div
    bind:this={inputNode}
    class="ink ink-input absolute {live && tool !== 'off' ? 'pointer-events-auto' : ''}"
    style="cursor: {cursor}; top: {-reach.top}px; right: {-reach.right}px; bottom: {-reach.bottom}px; left: {-reach.left}px"
    role="application"
    aria-label="Лист для рисования"
    onpointerdown={down}
