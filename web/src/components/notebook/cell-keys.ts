/**
 * Клавиши, которые правят СОСТАВ тетради, — и почему они правят его неохотно.
 *
 * Backspace на опустевшей ячейке удаляет её у всей комнаты, без истории и без
 * подтверждения. Это разумно ровно один раз — как последний штрих намеренного
 * стирания — и совершенно неразумно как побочный эффект удержания клавиши.
 */

export interface BackspaceInput {
  /** Документ ячейки пуст ДО этого нажатия. */
  empty: boolean
  /** Это автоповтор удерживаемой клавиши, а не отдельное нажатие. */
  repeat: boolean
}

/**
 * Удаляет ли этот Backspace ячейку.
 *
 * Автоповтор — нет, и это несущее «нет». Биндинг срабатывал на каждом keydown:
 * стоило документу опустеть, следующий повтор (через ~30 мс) уносил ячейку из
 * общей тетради, фокус синхронно переезжал в предыдущую — CodeMirror
 * восстанавливает её последний курсор, — и оставшиеся повторы стирали ЕЁ хвост,
 * а опустошив, удаляли и её. Человек, зажавший Backspace, чтобы стереть
 * `print(x)`, терял одну-две чужие ячейки вместе с выводом и не понимал, что
 * случилось; Ctrl+Z есть только в командном режиме и только у него самого.
 */
export function backspaceRemovesCell(input: BackspaceInput): boolean {
  return input.empty && !input.repeat
}

/**
 * И вторая половина: пустой текст — ещё не пустая ячейка.
 *
 * Под ней остаётся вывод: график, таблица, трейсбек, ради которого ячейку и
 * держат. Удаление уносит его у всей комнаты и вернуть нечем, а жест, которым
 * сюда пришли, — это стирание последней буквы, а не решение. Убрать такую
 * ячейку по-прежнему можно корзиной в тулбаре и двумя нажатиями `d` — оба
 * места об этом и говорят.
 */
export function emptyCellIsRemovable(outputs: number): boolean {
  return outputs === 0
}
