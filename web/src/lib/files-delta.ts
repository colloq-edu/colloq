/**
 * Дерево комнаты, собранное из перемен, а не присланное целиком.
 *
 * Список файлов рассылался полностью на каждую правку папки, а правит её всё
 * подряд: автосохранение редактора, `df.to_csv` в ячейке, `pip install` в
 * терминале. Один заведённый файл стоил комнате в пятьсот человек 3.0 МБ
 * (замерено) — при том что изменилась одна строка из двух тысяч.
 *
 * Здесь живёт ровно одно правило — как перемена ложится на список; считает её
 * сервер (server/src/workspace.ts · treeDelta). Порядок дерева однозначно
 * определён его составом (обход в глубину, папки перед файлами, по имени),
 * поэтому уцелевшие записи стоят друг относительно друга так же, как стояли, —
 * и порядок здесь не пересчитывается, а восстанавливается вставкой на место.
 *
 * Ни одной руны: это чистая функция над списком, и проверяется она без
 * браузера (tests/files-delta.test.mts).
 */
import type { FileEntry, FilesDelta } from '@shared/protocol'

/**
 * Список после перемены.
 *
 * Три шага в этом порядке и только в нём: убрать ушедшее, заменить
 * изменившееся, вставить новое по возрастанию `at`. Индексы новых записей —
 * места в ГОТОВОМ списке, так что вставлять их до удалений значило бы считать
 * места в чужом списке.
 *
 * Новый массив, а не правка на месте: список читают руны панели, и менять его
 * под ними — способ не перерисовать ничего.
 */
export function applyFilesDelta(files: readonly FileEntry[], delta: FilesDelta): FileEntry[] {
  const gone = new Set(delta.removed)
  const fresh = new Map<string, FileEntry>()
  for (const entry of delta.changed) fresh.set(entry.path, entry)
  const next: FileEntry[] = []
  for (const entry of files) {
    if (gone.has(entry.path)) continue
    next.push(fresh.get(entry.path) ?? entry)
  }
  // По возрастанию `at`: сервер шлёт их в этом порядке, но кадр приходит из
  // сети, а не из соседней строки, и держаться на его слове здесь незачем.
  const added = [...delta.added].sort((a, b) => a.at - b.at)
  for (const { at, entry } of added) {
    // Место за концом — в конец: дельта, разошедшаяся со списком, не должна
    // ронять панель. Разрыв номеров ловится раньше (session.svelte.ts), это
    // последняя черта.
    next.splice(Math.max(0, Math.min(at, next.length)), 0, entry)
  }
  return next
}
