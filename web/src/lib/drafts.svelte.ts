/**
 * То, что человек уже набрал, но ещё не отправил.
 *
 * Панели монтируются и размонтируются вместе со своими кнопками: закрыл
 * терминал — и половина набранной команды исчезла вместе с историей стрелки
 * вверх; свернул оракула, чтобы посмотреть на ячейку, о которой спрашиваешь, —
 * и вопрос стёрся. Всё это местное состояние компонента, и оно живёт ровно
 * столько, сколько компонент.
 *
 * Черновики переезжают сюда — в модуль, который живёт со вкладкой, а не с
 * панелью. В документ им не надо: это не общая работа, а недописанная строка
 * одного человека, и восстанавливать её после перезагрузки никто не просит.
 */

/** Команда в терминале плюс личная история стрелки вверх. */
export const terminalDraft = $state({
  command: '',
  /** Только свои команды: общая история в комнате была бы нечитаемой. */
  history: [] as string[],
  /** −1 — живая строка; иначе номер в истории. */
  at: -1,
  /** Строка, которую отложили, начав листать историю. */
  stashed: '',
})

/** Вопрос оракулу. */
export const oracleDraft = $state({ question: '' })
