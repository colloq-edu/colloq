/**
 * Что список файлов доказывает про общий экран, а что нет.
 *
 * Комната смотрит один документ вместе — доска, она же лекция, — и погасить его
 * можно только у всех сразу. Значит и решение «документа больше нет» дороже
 * обычного: оно выбрасывает зал из лекции в пустой центр, отвязывает
 * «Идём за Анной» и оставляет опоздавшего без того, о чём говорят.
 *
 * Принимать его по списку файлов можно ровно тогда, когда список ПОЛНЫЙ. Обход
 * папок на сервере упирается в потолок (server/src/workspace.ts · MAX_ENTRIES),
 * и обрезанный список — это «я не всё перечислил», а не «этого файла нет».
 * Разница стоила лекции: студент распаковывает датасет на три тысячи картинок,
 * `slides/lecture.pdf` не влезает в обход — и доска гаснет у всех, хотя на
 * сервере она стоит. У опоздавшего это происходит через миллисекунду после
 * входа: приветственная пачка шлёт `board`, а следом `files`.
 *
 * Сервер эту же ошибку у себя уже исправил — `forgetMissingBoard` в control.ts
 * спрашивает про сам путь (`statPath`), а не ищет его в дереве, — и о настоящей
 * пропаже объявляет отдельным кадром `board`. Здесь остаётся страховка на
 * случай, когда файл убрали мимо этого пути.
 */
import type { FileEntry } from '@shared/protocol'

/**
 * Пропал ли документ с общего экрана — по этому списку файлов.
 *
 * @param board  путь, который комната смотрит сейчас, или `null`.
 * @param files  список файлов из кадра `files` (или ответа `/files`).
 * @param truncated  список показан не целиком: обход упёрся в потолок.
 */
export function boardGone(
  board: string | null,
  files: readonly FileEntry[],
  truncated: boolean,
): boolean {
  if (!board) return false
  // «Не всё перечислил» — не свидетельство. Молчим и ждём кадра `board`.
  if (truncated) return false
  return !files.some((file) => !file.dir && file.path === board)
}
