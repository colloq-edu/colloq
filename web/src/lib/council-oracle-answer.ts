/**
 * Ответ оракула о классе — текст, в котором люди названы метками.
 *
 * Модель имён не видит: в кадре ей едут `S1…SN`, и она ссылается на людей
 * только ими (server/src/ai/council.ts · statusPrompt). Обратно метку в
 * человека превращает вот это: сервер прислал словарь `people` («S7» →
 * participantId), а пульт рисует на месте метки чип — имя студента или
 * «Вариант N», — по которому можно нажать и открыть его работу.
 *
 * Отдельным файлом и без единого импорта, потому что ломается это молча.
 * Наивная замена `text.replaceAll('S7', …)` съела бы `S7` внутри `CSS7`, а
 * `S7` внутри `S70` превратила бы в чужого человека: класс из семидесяти —
 * обычное дело, и преподаватель открыл бы не ту работу, ничего не заметив.
 *
 * Правило одно: метка — это `S` и цифры, стоящие отдельным словом, И только
 * если такая метка есть в словаре этого ответа. Метка, которой в словаре нет,
 * остаётся обычным текстом: нумерация живёт ровно один вопрос, и метка из
 * позапрошлого ответа не должна притвориться сегодняшней.
 */

/** Кусок ответа: либо текст как есть, либо человек, которого можно открыть. */
export type AnswerPiece =
  | { kind: 'text'; text: string }
  | { kind: 'person'; label: string; participantId: string }

/**
 * `\b` с обеих сторон — это и есть всё правило границ.
 *
 * Перед `S`: в `CSS7` между `S` и `S` границы нет (обе — буквы), и метка там
 * не начинается. После цифр: `S7,` и `(S7)` — границы есть, `S70` жадным
 * `\d+` берётся целиком и в словаре не находится.
 */
const LABEL = /\bS\d+\b/g

/**
 * Разложить ответ на текст и людей. Пустой текст — пустой список; текст без
 * известных меток — один кусок целиком (замена не должна резать абзац на части
 * там, где рисовать всё равно нечего).
 */
export function splitAnswer(text: string, people: Record<string, string>): AnswerPiece[] {
  const pieces: AnswerPiece[] = []
  let at = 0
  for (const found of text.matchAll(LABEL)) {
    const participantId = people[found[0]]
    if (!participantId || found.index === undefined) continue
    if (found.index > at) pieces.push({ kind: 'text', text: text.slice(at, found.index) })
    pieces.push({ kind: 'person', label: found[0], participantId })
    at = found.index + found[0].length
  }
  if (at < text.length) pieces.push({ kind: 'text', text: text.slice(at) })
  return pieces
}
