/**
 * Русское числительное: один шаг, два шага, пять шагов.
 *
 * Отдельным файлом, потому что подписей с числом на экранах больше одной, а
 * писались они тернарником «=== 1 ? то : это», который врёт на каждом втором
 * числе: «5 шага», «11 шага», «21 шагов». Правило одно на всех и целиком здесь:
 * единица, кроме одиннадцати; двойка-четвёрка, кроме двенадцати-четырнадцати;
 * всё остальное.
 *
 * Возвращает СЛОВО, а не «число слово»: у страницы курса единственное число
 * пишется словом («одна страница»), и подставить его туда может только тот, кто
 * строит фразу.
 */
export function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10
  const mod100 = n % 100
  if (mod10 === 1 && mod100 !== 11) return one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few
  return many
}
