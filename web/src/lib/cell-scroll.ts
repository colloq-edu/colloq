/**
 * Две вещи про прокрутку тетради, которые считаются числами, а не браузером.
 *
 * ПЕРВАЯ — куда везти экран, когда переходят на соседнюю ячейку. Раньше это
 * делал `scrollIntoView({ block: 'nearest' })`, и «nearest» — ровно то слово,
 * из-за которого Shift+Enter попадал куда попало: браузер двигает экран НА
 * МИНИМУМ, поэтому ячейка ниже экрана приезжает нижним краем к нижнему краю
 * (видно последнюю строку из сорока), а ячейка выше экрана — верхним краем
 * впритык к верхнему, и плавающий тулбар, который висит НАД ячейкой, уезжает
 * за край совсем. Здесь вместо «как-нибудь видно» считается одно определённое
 * место: верх ячейки под верхом контейнера, с местом под тулбар и просветом.
 *
 * ВТОРАЯ — на сколько подвинуть прокрутку, когда что-то выше экрана поменяло
 * высоту. Это работа браузерного scroll anchoring, и в тетради он её не делает
 * (замерено: отложенная ячейка выше экрана распрямляется с 240 px до 809,
 * `scrollTop` не меняется ни на пиксель, весь экран уезжает на 569). Поэтому
 * якорь свой, а браузерный выключен явно — иначе однажды поправят оба и уедет
 * вдвое.
 *
 * Модуль чистый и без DOM: сюда ходит тест. Геометрию собирает вызывающий.
 */

/** Просвет между тулбаром и верхом контейнера: ячейка не должна упираться. */
export const BREATH = 14

/**
 * Сколько занимает тулбар у ячейки, которая ещё не построена.
 *
 * У припаркованной и у отложенной ячейки тулбара в DOM нет вовсе, а место под
 * него нужно уже сейчас. Число — высота настоящего ряда (кнопки 24 px плюс
 * `py-0.5` с двух сторон), проверенная на стенде.
 */
export const TOOLBAR_FALLBACK = 28

/** Окно прокрутки: края в координатах экрана и текущее смещение. */
export interface Frame {
  top: number
  bottom: number
  scrollTop: number
}

/** Ячейка, к которой едем: края в координатах экрана и высота её тулбара. */
export interface CellBox {
  top: number
  bottom: number
  toolbar: number
}

/**
 * Целевой `scrollTop` — или `null`, если экран трогать не надо.
 *
 * Не трогать — не мелочь и не оптимизация: переход на соседнюю ячейку, которая
 * и так вся на виду, не должен двигать под человеком ни строки. Именно это
 * ломал `scrollIntoView`: он молчал, пока ячейка видна ЦЕЛИКОМ, но тулбар в
 * «видно» не входит, и ячейка у самого верха всё равно уезжала.
 */
export function advanceTarget(frame: Frame, cell: CellBox): number | null {
  const room = cell.toolbar + BREATH
  const wanted = advanceTop(frame, cell)
  // Ячейка вместе с тулбаром уже на экране целиком.
  if (cell.top - room >= frame.top && cell.bottom <= frame.bottom) return null
  // Уже стоит там, куда бы её и повезли: округление — не повод для анимации.
  if (Math.abs(wanted - frame.scrollTop) <= 1) return null
  return wanted
}

/**
 * То же место, но без вопроса «а надо ли ехать».
 *
 * Нужно, пока ход ИДЁТ: запущенная ячейка за эти кадры теряет строку «без
 * номера» и меняет вывод, соседка ниже съезжает, и цель, посчитанная в начале,
 * устаревает. Пересчитать её по живой геометрии точнее, чем копить поправки:
 * ответ не зависит от того, сколько уже проехали.
 */
export function advanceTop(frame: Frame, cell: CellBox): number {
  return Math.max(0, frame.scrollTop + (cell.top - frame.top) - (cell.toolbar + BREATH))
}

/** Ячейка, поменявшая высоту: где её верх в координатах прокрутки и на сколько. */
export interface HeightChange {
  top: number
  delta: number
}

/**
 * На сколько подвинуть прокрутку, чтобы экран остался на месте.
 *
 * Считается то, что НАЧИНАЕТСЯ выше верхнего края экрана: ячейка раскладывается
 * сверху вниз, значит всё, что стоит после её верха, поехало ровно на `delta`,
 * — и видимая часть экрана в том числе. Ячейка, чей верх на экране или ниже,
 * растёт у человека на глазах: там ничего двигать не надо, иначе поправка сама
 * станет рывком.
 *
 * Строгое «<» — не придирка: ячейка, начинающаяся ровно по верхнему краю,
 * растёт целиком внутрь экрана.
 */
export function anchorShift(changes: readonly HeightChange[], scrollTop: number): number {
  let shift = 0
  for (const change of changes) if (change.top < scrollTop) shift += change.delta
  return shift
}
