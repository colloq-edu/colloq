/**
 * «Вы 37-й» — числом, а не полным листом.
 *
 * Номер в очереди двигается у каждого ждущего на каждый конец любой работы
 * ядра, и раньше сервер вёз ради него весь лист (`council:mine`): на пятистах
 * попытках один досчитавшийся запуск — пятьсот листов, в каждом текст попытки,
 * задание и письма преподавателя ради одного числа. Теперь приезжает само
 * число (`council:queue`), и всё, что с ним надо сделать, — здесь.
 *
 * Ни одной руны: чистая правка снимка листов, проверяется без браузера
 * (tests/council-queue-bulk.test.mts).
 */
import type { CouncilMine } from '@shared/protocol'

/**
 * Лист этой ячейки — с новым номером в очереди.
 *
 * `at === null` — в очереди человека больше нет: его попытка дошла до ядра, и
 * «считается сейчас» говорит `run.state`, а не место в очереди.
 *
 * Правится только то, что действительно сменилось: снимок листов заменяется
 * целиком и будит перерисовку всех карточек консилиума — на своей ячейке это
 * редактор под руками автора. Совпало — возвращается тот же объект.
 *
 * Листа по ячейке нет — ставить номер некуда: лист приедет своим кадром и
 * привезёт номер с собой.
 */
export function withQueuePosition(
  mine: Record<string, CouncilMine>,
  cellId: string,
  at: number | null,
): Record<string, CouncilMine> {
  const sheet = mine[cellId]
  if (!sheet || sheet.queue === at) return mine
  return { ...mine, [cellId]: { ...sheet, queue: at } }
}
