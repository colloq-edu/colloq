#!/usr/bin/env bash
#
# Выкладка лендинга.
#
# Существует ради одной строки — той, что штампует версию в ссылку на
# таблицу стилей. Перед Pages стоит Cloudflare, и Pages отдаёт styles.css с
# max-age=14400: четыре часа читатели видят прежнее оформление, хотя новое
# уже выложено. Токен в .env умеет читать зону, но не чистить кэш, так что
# сбросить его отсюда нельзя.
#
# HTML при этом живёт 600 секунд и на границе не кэшируется вовсе
# (cf-cache-status: DYNAMIC). Значит, достаточно, чтобы свежий HTML показывал
# на другой адрес: ?v=<хеш файла> меняется ровно тогда, когда меняется сам
# файл, промахивается мимо кэша и подтягивает новую версию за минуты.
#
# Шрифты версии не требуют: их имена уже содержат начертание, и меняются они
# только вместе с именем.
set -euo pipefail
cd "$(dirname "$0")"

hash=$(md5 -q styles.css | cut -c1-8)
# Заменяем и голую ссылку, и уже проштампованную — скрипт должен быть
# идемпотентным, иначе второй запуск подряд ломает адрес.
perl -pi -e "s{href=\"styles\.css(\?v=[0-9a-f]+)?\"}{href=\"styles.css?v=$hash\"}" index.html

if [[ -n "$(git status --porcelain)" ]]; then
  git add -A
  git commit -q -m "${1:-Обновление лендинга}"
fi
git push -q origin main
echo "выложено, styles.css?v=$hash"
