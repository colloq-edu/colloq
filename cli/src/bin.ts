#!/usr/bin/env node
/**
 * Точка входа команды `colloq` — и единственная безусловная.
 *
 * main.ts запускает себя сам, но только узнав своё имя в argv[1]
 * (`…/cli/src/main.ts` или `.js`): так его зовут из исходников
 * (`node --import tsx cli/src/main.ts`), и так же он молчит, когда его просто
 * импортируют тесты. У пакета имя другое. Собранный одним файлом бандл лежит
 * где угодно и зовётся как угодно — `colloq`, `colloq-cli`, полный путь внутри
 * venv, — и проверка имени в нём не срабатывает НИКОГДА: команда завершалась
 * кодом 0, не напечатав ни строки, и это выглядело как «сработало». Поэтому
 * у пакета своя точка входа, без единого условия: импортировать main и позвать.
 *
 * Здесь нет ничего, кроме запуска: весь разбор argv, все отказы и весь вывод —
 * в main.ts. Код возврата ставится через process.exitCode, а не process.exit:
 * ранний exit обрывал бы ребёнка, которому sh пересылает сигналы и чей конец
 * ждёт, — та же причина, что в хвосте main.ts.
 */
import { cli } from './main.js'

process.exitCode = await cli(process.argv.slice(2))
